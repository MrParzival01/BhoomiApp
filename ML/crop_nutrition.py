def _convert_to_acre(hectare_value):
    return round(hectare_value / 2.5, 2)


def _convert_to_hectare(acre_value):
    return round(acre_value * 2.5, 2)


def calculate_fertilizer_doses(npk_recommended, kg=100):
    n, p, k = map(float, npk_recommended.split(":"))

    mop_dose  = (kg / 60) * k
    dap_dose  = (kg / 46) * p
    urea_dose = (100 / 46) * (n - ((18 / 100) * dap_dose))
    urea_dose = max(0.0, urea_dose)
    ssp_dose  = (p / 16) * kg

    return (
        round(mop_dose,  2), _convert_to_acre(mop_dose),
        round(dap_dose,  2), _convert_to_acre(dap_dose),
        round(urea_dose, 2), _convert_to_acre(urea_dose),
        round(ssp_dose,  2), _convert_to_acre(ssp_dose),
    )


def calc_soil_parameters(ph, ec, oc):
    if ph < 6.5 and ec < 4:
        remedy = "Apply lime"
    elif ph > 7.7 and ec < 8.5:
        remedy = "Remove salts with leaching and drainage"
    elif ph > 8.5 and ec < 4:
        remedy = "Gypsum application required"
    else:
        remedy = "No remedy needed"

    if oc < 0.5:
        fertility = "Low fertile, recommend green manure"
    elif oc < 0.75:
        fertility = "Medium fertile, soil is fertile"
    else:
        fertility = "High fertile, soil is fertile"

    return remedy, fertility


def calc_fymanure(frequency):
    if frequency == "Annual":
        return _convert_to_hectare(4)
    return _convert_to_hectare(10)


def _npk_is_valid(n, p, k):
    return not ((n > 1000 or n < 1) and (p > 1000 or p < 1) and (k > 1000 or k < 1))


def _get_n_value(n_input, n_dict):
    n_dict = float(n_dict)
    if n_input < 280:
        return n_dict + 0.25 * n_dict
    if n_input > 560:
        return n_dict - 0.25 * n_dict
    return n_dict


def _get_p_value(p_input, p_dict):
    p_dict = float(p_dict)
    if p_input < 22:
        return p_dict + 0.25 * p_dict
    if p_input > 56:
        return p_dict - 0.25 * p_dict
    return p_dict


def _get_k_value(k_input, k_dict):
    k_dict = float(k_dict)
    if k_input < 141:
        return k_dict + 0.25 * k_dict
    if k_input > 336:
        return k_dict - 0.25 * k_dict
    return k_dict


def get_crop_urea_dap_mop_dose(n, p, k, ph, ec, oc, crop):
    """
    Returns fertilizer doses and soil recommendations for a crop.

    Parameters
    ----------
    n, p, k : float  Soil NPK values (kg/ha). Pass 0 or None if unavailable.
    ph      : float  Soil pH  (or None)
    ec      : float  Electrical conductivity (or None)
    oc      : float  Organic carbon %  (or None)
    crop    : str    Crop name — must be a key in the crops dict

    Returns
    -------
    dict with keys:
        crop_fertilizer : list of dose lines per stage
        fym             : list of FYM + target yield lines
    """
    if crop not in crops:
        return {"error": f"'{crop}' not found. Call get_crop_list() for valid names."}

    dict_crop    = crops[crop]
    crop_n_p_ks  = dict_crop["npk"]
    n            = n or 0
    p            = p or 0
    k            = k or 0

    if _npk_is_valid(n, p, k):
        adjusted = [
            f"{_get_n_value(n, v.split(':')[0])}:"
            f"{_get_p_value(p, v.split(':')[1])}:"
            f"{_get_k_value(k, v.split(':')[2])}"
            for v in crop_n_p_ks
        ]
    else:
        adjusted = crop_n_p_ks

    fertilizer_rows = []
    for i, npk_str in enumerate(adjusted):
        mop, mop_a, dap, dap_a, urea, urea_a, ssp, ssp_a = calculate_fertilizer_doses(npk_str)
        lines = [
            f"Urea : {urea} kg/hectare  {urea_a} kg/acre",
            f"DAP  : {dap}  kg/hectare  {dap_a}  kg/acre",
            f"MOP  : {mop}  kg/hectare  {mop_a}  kg/acre",
            f"SSP  : {ssp}  kg/hectare  {ssp_a}  kg/acre",
        ]
        if "duration" in dict_crop:
            lines.insert(0, f"For {dict_crop['duration'][i]}")
        fertilizer_rows.append(lines)

    fym_rows = []
    fym = calc_fymanure(dict_crop["frequency"])
    has_soil = ph and ec and oc
    remedy = fertility_label = None
    if has_soil:
        remedy, fertility_label = calc_soil_parameters(ph, ec, oc)

    for target_yield in dict_crop["target_yield"]:
        row = []
        if has_soil:
            row += [f"Soil remedy   : {remedy}", f"Soil fertility: {fertility_label}"]
        row += [f"FYM           : {fym} tons/hectare", f"Target yield  : {target_yield}"]
        fym_rows.append(row)

    return {"crop_fertilizer": fertilizer_rows, "fym": fym_rows}


def get_crop_list(api=False):
    """Return sorted crop names. api=True yields plain strings, else (name, name) tuples."""
    sorted_crops = sorted(crops)
    return (crop if api else (crop, crop) for crop in sorted_crops)